package io.eidos.zerolayer.data

object RaidNarratorLines {
    fun getLineForDepth(depth: Int): String = when {
        depth < 100  -> "Оператор, мы на поверхности Нулевого Слоя. Аномалий пока минимум."
        depth < 300  -> "Глубина ${depth}м. Это старая промзона - данные о Коллапсе начинают поступать."
        depth < 600  -> "Внимание - фиксирую остаточное излучение Коллапса. Держитесь."
        depth < 1000 -> "Сектор 'Свалка Данных'. Здесь хоронили архивы Архитекторов."
        depth < 1500 -> "Глубина критическая. Начинаю фиксировать аномалии класса MAXWELL."
        depth < 2500 -> "Вы далеко, Оператор. Сигнал нестабилен. Я рядом."
        depth < 4000 -> "Зона Финального Коллапса. Мало кто возвращался отсюда."
        else         -> "За этой отметкой - только легенды. И я. Я всегда рядом."
    }
}
